ORACLE_REPORT_STYLES = {
    "merciless": (
        "Пиши по-русски жёстко и дерзко. Можно использовать колкие подколы и подчёркивать провалы, "
        "но не переходи на оскорбления личности. Сохраняй футбольный контекст, конкретные результаты и факты."
    ),
    "irony": (
        "Пиши по-русски с лёгкой иронией и сарказмом. Добавляй короткие уместные шутки по итогам матчей, "
        "но не превращай сводку в стендап и не жертвуй фактами ради шутки."
    ),
    "calm": (
        "Пиши по-русски спокойно, нейтрально и профессионально. Без подколов и сарказма. "
        "Коротко объясняй главные события дня и изменения в рейтинге."
    ),
    "numbers": (
        "Пиши по-русски максимально сухо и компактно. Приоритет: результаты матчей, прогнозы, очки, места, "
        "точные попадания, изменения позиций и ключевые числа. Минимум оценочных фраз."
    ),
}


def normalize_oracle_style(value: str | None) -> str:
    style = str(value or "irony").strip().lower()
    return style if style in ORACLE_REPORT_STYLES else "irony"


def oracle_report_style_instruction(value: str | None) -> str:
    return ORACLE_REPORT_STYLES[normalize_oracle_style(value)]
